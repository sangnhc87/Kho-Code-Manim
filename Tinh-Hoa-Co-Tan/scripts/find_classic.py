# Let's define a well known classic endgame:
# "Đơn Binh Hòa Đơn Tượng" (Single Pawn draws against Single Elephant).
# This is a very high quality educational endgame because it teaches that a pawn on the center file (e-file) can draw against an Elephant if it positions itself correctly, but if it moves incorrectly, it loses? No, a single pawn cannot win. It's always a draw.

# What about "Đơn Pháo Thắng Đơn Sĩ"?
# Single Cannon wins against Single Advisor.
# Wait, Cannon cannot win against a single Advisor because it has no mount!
# But wait! Cannon CAN use the ENEMY ADVISOR as a mount to check the enemy King!
# YES! "Đơn Pháo Khéo Thắng Đơn Sĩ" is a VERY famous classic endgame!
# How does it work?
# Red has King and Cannon. Black has King and Advisor.
# Red uses Black's Advisor as a mount (ngòi) to checkmate Black's King!
