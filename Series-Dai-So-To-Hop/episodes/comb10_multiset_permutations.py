def formula_image(name):
    image_path=ROOT/'assets'/'comb10v2'/f'{name}.png'
    if not image_path.exists():
        raise FileNotFoundError(f'Chưa có công thức Typst: {image_path}. Hãy chạy prepare_comb10_v2.py.')
    graphic=ImageMobject(str(image_path))
    graphic.scale_to_fit_width(min(graphic.width, 5.62))
    if graphic.height>.80:graphic.scale_to_fit_height(.80)
    graphic.move_to((RX,-1.10,0))
    return graphic


class COMB10(Scene):
    def setup(self):
        voice_manifest=ROOT/'voice'/'comb10_voice_manifest.json'
        if not voice_manifest.exists():
            raise FileNotFoundError('Hãy chạy: python scripts/prepare_comb10_v2.py --voice off')
        self.meta=json.loads(voice_manifest.read_text(encoding='utf-8'))
        if self.meta['beats']!=len(BEATS):raise ValueError('Voice manifest mismatch')
        self.previous=None
        self.add(word('SANG MATH  /  ĐẠI SỐ TỔ HỢP',-3.7,3.62,19,C['cyan'],True,6.10))
        self.add(word('COMB10  /  HOÁN VỊ LẶP',3.68,3.62,17,C['muted'],True,5.1))
        self.add(Line((-6.85,3.32,0),(6.85,3.32,0),color=C['line'],stroke_width=1.1))
        for cx,width in ((LX,6.18),(RX,6.46)):
            bg=RoundedRectangle(width=width,height=6.16,corner_radius=.16,
                stroke_color=C['line'],stroke_width=1.3,
                fill_color=C['panel'],fill_opacity=1)
            bg.move_to((cx,0,0));self.add(bg)
        self.add(Line((-6.85,-3.32,0),(6.85,-3.32,0),color=C['line'],stroke_width=1.1))

    def make_right(self,b,index):
        heading=VGroup(word(CHAPTER_LABELS[b.section],RX,2.67,15,C['purple'],True,5.78),
                       word(b.heading,RX,2.05,20,C['gold'],True,5.72))
        statements=VGroup(*[word('• '+line,RX,1.24-i*.60,17,C['text'],False,5.75)
                            for i,line in enumerate(b.lines)])
        equation=formula_image(b.formula) if b.formula else word('QUAN SÁT → CHỨNG MINH',RX,-1.10,17,C['cyan'],True,5.65)
        conclusion=VGroup(Line((.25,-1.76,0),(6.17,-1.76,0),color=C['line'],stroke_width=1.1),
                         word(b.takeaway,RX,-2.35,16,C['green'],True,5.76))
        counter=word(f'{index+1:02d} / {len(BEATS)}',0,-3.70,15,C['muted'],True)
        return heading,statements,equation,conclusion,counter

    def show_beat(self,index,b):
        metadata=self.meta['clips'][f'{index:03}']
        if metadata.get('file'):
            audio=ROOT/'voice'/metadata['file']
            if not audio.is_file():raise FileNotFoundError(audio)
            self.add_sound(str(audio))
        duration=max(b.min_seconds,float(metadata.get('duration',0))+.85)
        art,focus=VIEWS[b.section](b.state)
        head,statements,eq,conclusion,counter=self.make_right(b,index)
        if self.previous is None:
            self.play(FadeIn(art),FadeIn(head),FadeIn(counter),run_time=1.0)
        else:
            oart,ohead,olines,oeq,oconc,ocounter=self.previous
            self.play(FadeOut(oart),FadeIn(art),FadeOut(ohead),FadeIn(head),
                      FadeOut(olines),FadeOut(oeq),FadeOut(oconc),
                      ReplacementTransform(ocounter,counter),run_time=1.0)
        special=0.0
        if b.section=='identity' and b.state==2:
            # A1 and A2 actually exchange positions: with labels these are
            # different permutations, but after deleting labels they coincide.
            self.play(Swap(art[1],art[2]),run_time=1.35)
            special=1.35
        self.play(Indicate(focus,color=C['gold'],scale_factor=1.06),run_time=1.6)
        for line in statements:
            self.play(FadeIn(line,shift=.08*UP),run_time=1.10)
        self.play(FadeIn(eq,shift=.08*UP),run_time=1.20)
        self.play(FadeIn(conclusion),run_time=.95)
        self.play(Circumscribe(conclusion[-1],color=C['green'],buff=.085),run_time=1.20)
        spent=1+special+1.6+3*1.10+1.20+.95+1.20
        if duration>spent:self.wait(duration-spent)
        self.previous=(art,head,statements,eq,conclusion,counter)

    def construct(self):
        for i,b in enumerate(BEATS):self.show_beat(i,b)
        self.play(*[FadeOut(x) for x in self.previous],run_time=1)
        ending=VGroup(word('COMB10  ·  HOÁN VỊ LẶP',0,.55,31,C['cyan'],True,11.5),
                      word('HIỂU ĐẾM TRÙNG TRƯỚC KHI DÙNG CÔNG THỨC',0,-.34,20,C['gold'],True,12.0))
        self.play(FadeIn(ending),run_time=1.35)
        self.wait(2.85)
