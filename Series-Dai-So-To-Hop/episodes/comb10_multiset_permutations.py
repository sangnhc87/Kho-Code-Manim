def banana_view(s):
    g=VGroup();headline(g,'BANANA · BA A, HAI N, MỘT B')
    chars='BANANA'
    cols=[C['gold'] if ch=='B' else C['cyan'] if ch=='A' else C['purple'] for ch in chars]
    tokens=token_strip(g,list(chars),1.58,.81,cols)
    for i,(t,color) in enumerate([('A × 3',C['cyan']),('N × 2',C['purple']),('B × 1',C['gold'])]):
        g.add(label(t,LX+(i-1)*1.8,.72,1.58,.61,color,17))
    # 6 x 10 layout: show a representative sample from all 60 results.
    samples=unique_words('BANANA')[:24]
    count=[0,0,0,8,16,24][s]
    tiles=mini_grid(g,samples,count,columns=6,top=.12,spacing_x=.86,spacing_y=.52,text_size=12)
    foot(g,'6! / (3! × 2!) = 60' if s>=4 else '720 CÁCH CÓ NHÃN, MỖI TỪ LẶP 12 LẦN')
    return g,(tiles[min(count-1,len(tiles)-1)] if count else tokens[min(s,5)])


def general_view(s):
    g=VGroup();headline(g,'CHỨNG MINH CÔNG THỨC TỔNG QUÁT')
    objects=[]
    seq=[('n vị trí',C['cyan']),('n! có nhãn',C['gold']),('k₁! lần',C['purple']),
         ('k₂! lần',C['purple']),('…',C['inactive'])]
    for j,(t,c) in enumerate(seq):
        x=LX + (j-2)*1.16
        box=label(t,x,1.48,1.05,.69,c,14)
        g.add(box);objects.append(box)
    for i in range(1,5):
        g.add(Arrow((LX+(i-2.5)*1.16,1.10,0),(LX+(i-1.5)*1.16,1.10,0),
                    color=C['line'],stroke_width=1.6,max_tip_length_to_length_ratio=.13))
    examples=[('TẤT CẢ KHÁC NHAU','n!'),('MỘT NHÓM GIỐNG NHAU','n! / k!'),
              ('NHIỀU NHÓM GIỐNG NHAU','CHIA TÍCH CÁC GIAI THỪA')]
    for j,(a,b) in enumerate(examples):
        y=.43-j*.78
        g.add(word(a,LX-1.2,y,14,C['muted'],True,3.25),
              label(b,LX+1.65,y,2.31,.61,C['green'] if j<=s//2 else C['inactive'],15))
    foot(g,'n = k₁ + k₂ + ··· + kᵣ' if s<3 else 'SỐ KẾT QUẢ = n! / (k₁! k₂! … kᵣ!)')
    return g,objects[min(s,4)]


