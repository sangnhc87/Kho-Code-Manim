def challenge_view(s):
    g=VGroup();headline(g,'AABBC · LOẠI CẶP AA / BB')
    chars='AABBC';cols=[C['cyan'],C['cyan'],C['purple'],C['purple'],C['gold']]
    tokens=token_strip(g,list(chars),1.61,.93,cols)
    arrangement=unique_words('AABBC')
    # Display all 30 results. Keep the condition visible through persistent color.
    flag={w for w in arrangement if 'AA' not in w}
    high=None if s<2 else flag if s==3 else {w for w in arrangement if 'AA' not in w and 'BB' not in w} if s==4 else flag
    tiles=mini_grid(g,arrangement,selected=30 if s>=2 else min(12,s*12),
                    columns=6,top=.85,spacing_x=.89,spacing_y=.51,text_size=11,
                    highlights=high)
    foot(g,'30 − 12 = 18' if s==3 else '30 − 12 − 12 + 6 = 12' if s>=4 else 'TỔNG CỘNG 30 HOÁN VỊ')
    return g,tiles[min(s*4,len(tiles)-1)] if tiles else tokens[0]

