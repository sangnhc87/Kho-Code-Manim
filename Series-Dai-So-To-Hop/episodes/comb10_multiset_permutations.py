def word(text, x, y, size=19, color=None, bold=False, max_width=None):
    t = Text(str(text), font=FONT, font_size=size, color=color or C['text'],
             weight='BOLD' if bold else 'NORMAL')
    if max_width and t.width > max_width:
        t.scale_to_fit_width(max_width)
    t.move_to((x, y, 0))
    return t


def label(text, x, y, w=0.84, h=0.66, color=None, font=20, fill=None):
    col = color or C['cyan']
    block = RoundedRectangle(width=w, height=h, corner_radius=.115,
                             stroke_color=col, stroke_width=1.8,
                             fill_color=fill or C['panel_alt'], fill_opacity=1)
    block.move_to((x, y, 0))
    value = word(text, x, y, font, C['text'], True, w-.10)
    return VGroup(block, value)


def headline(group, name):
    group.add(word(name, LX, 2.60, 16, C['cyan'], True, 5.56))


def foot(group, text):
    group.add(word(text, LX, -2.59, 15, C['gold'], True, 5.55))


def token_strip(group, letters, y=1.33, gap=.88, colors=None):
    objects=[]
    for i, ch in enumerate(letters):
        color = (colors[i] if colors else C['cyan'])
        x = LX + (i-(len(letters)-1)/2)*gap
        p=label(ch,x,y,.70,.76,color,20)
        group.add(p);objects.append(p)
    return objects


def mini_grid(group, strings, selected=None, columns=4, top=.45, spacing_x=1.26,
              spacing_y=.49, text_size=16, highlights=None, max_rows=None):
    objs=[]
    for i, s in enumerate(strings):
        if max_rows is not None and i//columns>=max_rows:break
        x=LX+(i%columns-(columns-1)/2)*spacing_x
        y=top-(i//columns)*spacing_y
        col=C['inactive']
        if highlights is not None:
            col=C['green'] if s in highlights else C['red'] if selected is not None else C['inactive']
        elif selected is not None and i<selected:
            col=C['green']
        p=label(s,x,y,spacing_x-.1,spacing_y-.07,col,text_size)
        group.add(p);objs.append(p)
    return objs


def boxes_at(group, texts, positions, y, colors, w=.9):
    objs=[]
    for text,x,color in zip(texts,positions,colors):
        p=label(text,x,y,w,.75,color,18)
        group.add(p);objs.append(p)
    return objs


def identity_view(s):
    g=VGroup();headline(g,'VẬT GIỐNG NHAU → HOÁN VỊ TRÙNG')
    tags=['A₁','A₂','B','C'] if s in (1,2) else ['A','A','B','C']
    colors=[C['cyan'],C['cyan'],C['gold'],C['purple']]
    objs=token_strip(g,tags,1.34,.94,colors)
    if s>=2:
        g.add(CurvedArrow((LX-.45,.84,0),(LX-1.43,.84,0),angle=-1.3,color=C['purple'],stroke_width=2.4))
        g.add(word('ĐỔI HAI A → CÙNG KẾT QUẢ',LX,.57,15,C['purple'],True,5.3))
    arrangements=unique_words('AABC')
    count=[0,0,0,4,12,12][s]
    grid=mini_grid(g,arrangements,count,columns=4,top=.16,spacing_x=1.37,spacing_y=.59,text_size=17)
    foot(g,'24 / 2! = 12 HOÁN VỊ' if s>=3 else 'THỬ GẮN NHÃN RỒI XOÁ NHÃN')
    focus=grid[min(max(count-1,0),len(grid)-1)] if grid else objs[min(s,3)]
    return g,focus


